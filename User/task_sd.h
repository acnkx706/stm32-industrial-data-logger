/*==============================================================================
 * task_SD —— SD 卡落盘任务（执行表 T2.3 / T2.5）
 *
 *  架构位置（已评审采纳）：
 *    task_ACQ(6) --队列--> task_PROC(2) --乒乓缓冲传指针--> task_SD(1) --> FatFs
 *
 *  ★ 优先级 1（最低业务级）的理由：卡写 busy 最坏 250ms，只有把 SD 操作压在
 *    最低优先级，这段慢才被隔离在 task_SD 里 —— ACQ→PROC 采集链永不阻塞。
 *  ★ 栈 **384 字（=1.5KB）**的理由：f_open/f_write 调用链 + sprintf 拼文件名
 *    实测占用几百字节；先给 256，实测后按"×1.5 定容"惯例【定到 384】✓
 *    （★ 2026-10-19 实测 `sdstk` 水位剩 76~84 字 ⇒ 【余量约 22% ✓ 够但偏紧】
 *      ★★ 原注释写的 256 是【定容之前】的值 ✗ 已修正 ✓）
 *
 *  ★ 铁律（_FS_REENTRANT=0 的前提）：全工程【只有本文件】允许调用 f_xxx
 *    和 diskio；其他任务想写卡，只能走 SD_LogEnqueue 交缓冲。
 *
 *  ── 与 task_PROC 的交接（乒乓双缓冲，改动点见 README 集成步骤 §3）──
 *    缓冲指针在两条队列间循环流转，任一时刻只在一个人手里（无拷贝、无竞争）：
 *    1. PROC 侧：SD_BufAcquire(&buf) 申请空缓冲 → 填 CSV 行 →
 *       SD_LogEnqueue(buf, len) 交给 task_SD
 *    2. task_SD 侧：从队列收 {指针,长度} → f_write → f_sync → 还回空闲队列
 *    缓冲定义在本文件（static 512B×2，全局放置不占任务栈，见执行表 RAM 总账）
 *============================================================================*/

#define TASK_SD_PRIO            1   /* 最低业务优先级：SD 慢被隔离在此，不碰采集链 */

/* ★★★★ 2026-10-13 加大 ✗：256 → **512 words**（★ 1KB → 2KB ✓）
 *
 *  ★ 为什么必须加 ✗：
 *    · ★ 实测【高水位只剩 **16 words**】✗✓!!
 *      （★ 从 `vTaskList()` 看：★ `SD  B  1  【16】  9` ✓）
 *    · ★★ 【16 words = 64 字节 ✗ 一次稍深的调用就会【栈溢出】】✓
 *      → ★★★ 【而 FreeRTOS 的栈溢出检测【只在【任务切换时】查 ✗
 *        溢出【可能已经【踩坏别的内存】了】✓✓
 *
 *  ★★ 栈被谁吃掉的 ✗（★ 都在 `task_sd.c` 的局部变量里 ✓）：
 *    · `uint8_t buf[256]`      ✗ 64 words（★ `SD_ReadLastLine` ✓）
 *    · `char    txt[224]`      ✗ 56 words（★ `SD_AppendEvidence` ✓）
 *    · `char    lastline[200]` ✗ 50 words（★ `sd_mount_and_open` ✓）
 *    → ★★★ 【最坏路径】✗：★ `sd_mount_and_open` 里【同时】活着
 *      `lastline[200]` 和它调用的 `SD_ReadLastLine` 的 `buf[256]`
 *      → 【200 + 256 = 456 字节 = 114 words】✓✓
 *      → 再加 FatFs 调用链 → 【正好只剩 16】✓
 *
 *  ★★★ 为什么【一步加到 512**✗：
 *    · ★ 1KB → 2KB ✗ 而【heap 还有 ~3.8KB 余量 ✗ 负担得起】✓
 *    · ★★ 【而且【以后【升级功能 / W25Q64 缓冲】还会往里加代码】✓
 *    → ★★★ 【留足余量 ✗ 不再反复调】✓✓
 *
 *  ★★★★ 以后想【省回来】✗ → 把上面那三个数组【改成 static】✓
 *    · ★ 能【省下约 114 words】✓
 *    · ★★ 【安全性】✗：task_SD 【只有一个实例 ✗ 这些函数不会重入】✓✓
 *    · ★★★ 【但【不是现在的事 ✗ 先保证不出事】✓
 *
 *  ★★★★ 2026-10-13 微调 ✗：512 → **384 words**
 *    · ★ 实测（★ Task list 第 4 列 = 栈余量 ✓）：
 *      · 栈 512 时 ✗ 余 **272 words** → 【实际用了 **240 words**】✓
 *    · ★★ 改成 384 ✗ → 【余量 = 384 − 240 = **144 words**】✓✓
 *      · ★★★ 144 words = 576 字节 ✗ 【对 SD 这条链【足够宽裕】】✓
 *    · ★★★★ 为什么【不继续往下砍**✗：
 *      · `PROC` 的余量是 72 words ✗ 那已经算"紧"了 ✓
 *      · ★★ 而【第三步"收固件 + 擦写 Flash"✗
 *        【还会往 task_SD 里加代码】✓✓
 *      → ★★★ 【留 144 words ✗ 是【给自己留余地】】✓
 *
 *  ★★★ 顺便【heap 账**✗：★ 512→384 words ✗
 *    省下 (512−384)×4 = **512 字节** ✓
 *    → ★★ free heap 从约 10736 【涨回约 11248】✓✓ */
/* ★ 2026-10-19 实测：`STAT ... sdstk=212` ⇒ 峰值只用了 172 字 ✓
 *   ⇒ 【384 字够用】✗ 加大的 512 已撤回 ✓（★ 省回 512 B RAM ✓）
 *   ★ 结论：E:09 【不是栈溢出】✗ 往别处查 ✓ */
#define TASK_SD_STACK_SIZE      448      /* ★★★ 2026-10-19 R4：384 → **448**（★ 反而加 ✓）
                                          *  ★ 实测最深 **324 字** ✗ 水位只剩 60/384 = **16%**
                                          *    ★ 而且那是【掉卡后重新挂载那趟】撑上去的
                                          *      （★ `f_mount` + `f_open` + `sprintf` 拼文件名 ✓）
                                          *  ★★ 324 × 1.3 ≈ 421 ⇒ 448 有 38% 余量 ✓✓
                                          *  ★★★ 交接文档早就写过"建议加到 448" ✗
                                          *    这次【实测坐实了】✓✓ */

#define SD_BUF_SIZE             512 /* 一块 = SD 卡一个扇区：写大块最省协议开销 */

/* 乒乓双缓冲：PROC 填其中一块，task_SD 写另一块，交替无拷贝
 * ★ 定义在 task_sd.c（全局 static 区），extern 只是为了 PROC 侧能填它 */
extern uint8_t g_sd_buf[2][SD_BUF_SIZE];

/* SD 卡故障标志：1 = 卡不在/连续写失败（丢批中），插回自动恢复后清 0
 * ★ volatile：DISP/PROC 只读它，task_SD 写它，不加会被编译器缓存进寄存器 */
extern volatile uint8_t g_sd_error;

/* ★ Y2 修复（第 6 课）：最近一次失败的原因码 —— g_sd_error 只能说"坏了"，
 *   它才能说"为什么"。当前喂进来的都是 FRESULT（f_mount/f_write/f_sync 的
 *   返回值，0~19；FR_OK=0/FR_NOT_READY=3/FR_DISK_ERR=1/FR_DENIED=7...），
 *   将来若接 SD 驱动原始错误码（SD_Result_t），需要再扩一位"来源域"区分。
 *   挂载成功时随 g_sd_error 一起清 0 —— OLED 上 E:00 = 无错误史。
 *   volatile：task_SD 写、DISP 只读，跨任务可见性由它保证 */
extern volatile uint8_t g_sd_last_err;

/*============================================================================
 *  ★★★★ 安全关机握手（★ 2026-10-13 深夜加 ✓）
 *
 *  ★★★ 为什么要这么一套 ✗✓（★ 关掉一个"正在写的文件"不能乱来 ✓）：
 *    · ★ 拔电就走 ✗：★ 数据其实【每批都 f_sync 了 ✗ 最多丢一批】✓
 *      ★★ 但【文件【从来没被 f_close**✗ 目录项/簇链是"半开"状态】✓✓
 *    · ★★★ 所以"安全关机"要做的【不是"抢救数据"✗
 *      而是【"把卷干净地卸下来 ✗ 并且【明确告诉人现在可以拔"】】✓✓
 *
 *  ★★ 三段握手（★ 谁负责什么一目了然 ✓）✗：
 *    · ★ **task_KEY**   ✗ 长按电源键 → 置 `g_shutdown_req = 1`
 *      ✗ 同时置 `g_pause = 1`（★ 【先停采集 ✗ 不再产生新数据】✓）
 *    · ★★ **task_SD**   ✗ 收到请求 → 【把队列里剩的写完】→ `f_sync`
 *      → `f_close` → `f_mount(NULL)` → 置 `g_shutdown_done = 1` ✓
 *    · ★★★ **task_DISP** ✗ 看到 done → 整屏 `SAFE TO OFF` + 长响一声 ✓
 *
 *  ★★★★ 撤销（恢复记录）✗：★ 再长按一次 → 清 `g_shutdown_req` ✓
 *    → 【SD 任务【会按它原有的逻辑自己重挂】**✗ 不用写新代码 ✓✓
 *      （★ 因为 `mounted` 已经被清 0 ✗ 循环顶部的 `if (!mounted)` 会接管 ✓）
 *
 *  ★ 为什么放在【本头文件】✗：★ `freertos_demo.c` 【已经 include 它】✓
 *    （★ 和 `g_sd_error` 同一个位置 ✗ 不为此新开文件 ✓✓）
 *==========================================================================*/
extern volatile uint8_t g_shutdown_req;    /* ★ 1 = 请求安全关机 ✓ */
extern volatile uint8_t g_shutdown_done;   /* ★ 1 = 已经落盘关文件 ✗ 可以断电 ✓ */

/* ★★★ 2026-10-18 加：这次关机【真的存住了吗】✗
 *   · 1 = 文件 f_close 成功 ✓
 *   · 0 = 没存住 / 从没挂载过 ⇒ 屏上【不许】写 `DATA SAVED` ✓
 *   ★ 为什么单独一个标志 ✗：`g_shutdown_done` 只说"我处理完了"✗
 *     分不清"存好了"和"根本没卡"✓✓ */
extern volatile uint8_t g_shutdown_saved;

void task_sd_Init(void);                /* 建交接队列+信号量（调度器启动【前】调一次） */
