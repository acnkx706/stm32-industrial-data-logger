#ifndef __GOLDEN_H
#define __GOLDEN_H

#include "stm32f10x.h"

/*==============================================================================
 *  ★★★★★ 金副本（Golden Copy）—— 版本备份与回退（★ 2026-10-14 建 ✓）
 *
 *  ★★★★ 它解决什么 ✗✓：
 *    · ★ App 【坏了 / 卡死了】✗ 现在只有两条路 ✓：
 *      · 进 Bootloader（★ 按键自救 ✓）→ 【但还是需要一台 PC + 一个固件】✓
 *      · ★★ 或者 【拆下来用探针重烧】✓
 *    · ★★★ 有金副本之后 ✗ 【Boot 能【自己把上一版装回来】】✓✓
 *      → 【"任意时刻都能自愈"】✓
 *
 *  ★★★★★ 设计的灵魂：【"什么时候算一个好版本"】**✗✓
 *    ★★ 如果用"永远跟着最新版本走"✗ → 【升级到坏版本 ✗ 备份立刻被覆盖 ✗
 *      【回退就【无从谈起】】】✓✓
 *    → ★★★ 所以本模块的规则【只有四条】✗✓：
 *    ```
 *    ① 槽【空的】           → 【慢慢静默地填上当前这一版】✓
 *    ② 槽【已有内容】        → 【一个字节都不动】✓（★ 它代表"上一版"✓）
 *    ③ 【要升级了】          → 【把【当前正在跑的】这一版写进去】（★ 覆盖 ✓）
 *    ④ 【PC 发 `B`】         → 【清空 + 把当前版本的 CRC 记成【黑名单】】✓
 *    ```
 *    ★★★★ ①② 分开是关键 ✗✓：
 *      · 【后台填充【只负责"从无到有"】】✓
 *      · 【"从旧换新"【只能由【升级流程】显式做】】✓✓
 *        （★ 因为【只有升级那一刻 ✗ 我们【确定】旧版本是好版本】✓）
 *
 *  ★★★★ 为什么【第 ④ 条要"记黑名单"✗ 光清空不够】✗✓：
 *    · ★ 只清空 ✗ → 【App 还在跑 ✗ 【下一拍它又把自己慢慢填回去了】】✓✗
 *    · ★★ 记下"这一版的 CRC" ✗ 规则改成 ✗
 *      【槽空 且 我的 CRC ≠ 黑名单 → 才自动填】✓✓
 *    → ★★★ 效果 ✗：
 *      · 【这一版（有 bug 的那个）【永远不会被自动备份】】✓
 *      · 【而你烧进好版本后（CRC 不同）✗ 它自己就会填上】✓✓
 *
 *  ★★★★★ 一个"和 Bootloader 同源"的技巧 ✗✓：
 *    ★ 备份的【头（magic/size/crc）【最后才写】**✓
 *    → 【传到一半掉电 ✗ 头没写 ✗ 这份备份【天然无效】】✓
 *    → ★★ 【下次开机看到"没有有效头"✗ 从头重传】✓✓
 *      （★ 和"先擦第 0 页 ✗ 最后写回"是【完全同一个思想】✓）
 *
 *  ★★★ W25Q64 布局（★ 按 **64KB 块**对齐 ✗ 因为那是【擦除单位】✓）✗：
 *    ```
 *    0x000000 ~ 0x000FFF   4KB  【头】= [64B 头][其余留空]
 *                                ↑ ★★ 审计 G8：让它【独占一个扇区】✓
 *    0x001000 ~ 0x00FFFF  ~60KB 【镜像】（56KB）
 *    0x010000 ~ 0x010FFF   4KB  【元数据】= 黑名单等（★ 极少写 ✓）
 *    0x020000 ~ ...              【历史版本】（★ v2 ✓）
 *    0x7FF000 ~ 0x7FFFFF   4KB  【自检扇区】（★ 已经在用 ✓）
 *    ```
 *    ★★★★ 为什么【镜像要退到 0x001000**✗✓（★ 审计 G8 ✓）✗：
 *      · ★ 原方案把镜像放在 `0x000100` ✗ 【和头【同一个 4KB 扇区】】✓
 *      · ★★ 于是"清备份"时 `EraseSector(0x000000)` ✗
 *        【会【连带擦掉镜像的头 3.9KB】✗（★ 正是向量表那段 ✓）】✓✓
 *      · ★★★ 现在这样 ✗ 【头独占 0x000~0xFFF ✗ 镜像从 0x1000 起】✓
 *        → 【"清头"和"毁镜像"【在物理上解耦】】✓✓
 *        （★ 而【整体擦除仍然是一个 64KB 块 ✗ 不用多擦一次】✓）
 *
 *  ★★★★ 分工（★ 关键收益 ✗ 见下 ✓）：
 *    · ★ **App（本模块）** ✗ 干【所有"写"的活】✓
 *      （★ 后台填充 / 升级前写 / 清 / 黑名单 ✓）
 *    · ★★ **Boot** ✗ 【只"读 + 恢复"✗ 永远不写 W25Q64】✓✓
 *    → ★★★ 【Boot 只加 ~1KB ✗ 8KB 里【余 1,844 B】【守得住】】✓✓
 *============================================================================*/

/* ---- 镜像位置（★ **必须和 `Boot\boot_config.h` 一致**✗✓）-------------------
 *  ⚠️ ★★★★ 这两个值【Boot 和 App 各有一份】✗
 *    【改一边【必须改另一边 ✗ 否则 Boot 恢复时会【对不上地址】】】✓✓ */
#define GOLDEN_APP_BASE      0x08004000u
/* ★★★★ 2026-10-14 改：随 CBT6 新分区一起搬（56KB → 112KB ✓）
 *   · 112 × 1024 = 【114688】✓ 正好是 App 的新分区长度（0x1C000 ✓）
 *   ★★★ 【必须和 Boot\boot_config.h 的 APP_SIZE 严格一致】✗
 *     因为 Boot 校验备份时的判据是「magic == "GOLD" 且 size == APP_SIZE」✓
 *     （见 Boot\boot_golden.h:45 ✓）
 *   ★★ 不一致的后果：App 写 112KB ✗ Boot 认 56KB ✗
 *      → 【备份被判为无效 ✗ 回退功能静默失效】✓ 而且是"看起来正常"的那种失效 ✓✓ */
#define GOLDEN_APP_SIZE      (112u * 1024u)          /* ★ 57344 ✓ */

/* ---- W25Q64 里的地址（★ 见上面的布局图 ✓）-------------------------------- */
#define GOLDEN_ADDR_HDR      0x000000u              /* ★ 头（★ magic 最后写 ✗ 独占一扇区 ✓）*/
#define GOLDEN_ADDR_IMG      0x001000u              /* ★★ 镜像（★ 审计 G8：与头分扇区 ✓）*/
#define GOLDEN_ADDR_META     0x020000u              /* ★ 元数据扇区 ✓ */

#define GOLDEN_IMG_OFFSET    0x001000u              /* ★ 镜像在【块内】的偏移 ✓ */
#define GOLDEN_BLOCK_SIZE    0x10000u               /* ★ 64KB ✓ */

/* ---- 魔数（★ 不用简单的 1 ✗ 理由同 boot_flag.h ✓）------------------------ */
#define GOLDEN_HDR_MAGIC     0x474F4C44u            /* ★ "GOLD" ✓ */
#define GOLDEN_META_MAGIC    0x4D455441u            /* ★ "META" ✓ */
#define GOLDEN_CRC_NONE      0xFFFFu                /* ★ "没有黑名单" ✓ */

/* ---- 后台填充的速率（★ 用户 2026-10-14 定 ✗ 每 500ms 一页 ✓）--------------
 *  ★ 一整份 56KB = **219 页**（★ 每页 256 B ✓）
 *    → 【219 × 500ms ≈ **110 秒**】✓
 *  ★★ CPU 占用 ✗：★ 每页软件 SPI 约 1.4ms ✗
 *    → 【1.4ms / 500ms ≈ **0.3%**】✗ 【真正"静默"】✓✓
 *  ★★★ 为什么【不用更慢**✗：★ 太慢的话 ✗
 *    【第一次上电后【很久都没有备份可用】✗ 那段时间【等于没有保护】】✓✓
 *  ★★★★ 【而且它是【低优先级任务】✗
 *    【采集任务会【抢占】它 ✗ 不会拖慢数据链】✓✓ */
#define GOLDEN_PAGE_INTERVAL_MS   500u

/*==============================================================================
 *  ★★★★ 对外接口
 *============================================================================*/

/* ★★ 初始化：★ 建任务前调一次 ✗ 读元数据/算自己的 CRC ✓
 *  ★ 返回 1 = W25Q64 在位（★ 不在位就【整个功能自动静默关闭】✓）*/
uint8_t Golden_Init(void);

/* ★★★★ 后台填充任务（★ 低优先级 ✗ 慢慢传 ✓）
 *  ★ 逻辑 ✗：
 *    · 已经备份过了（★ CRC 一致 ✓）→ 【直接睡】✓
 *    · 被列入黑名单 → 【睡】✓
 *    · 否则 → 【擦块 → 逐页传 → 最后写头】→ 睡 ✓✓ */
void    Golden_Task(void);

/* ★★★★ 【升级前】把当前这一版写进备份（★ 同步 ✗ 约 2~3 秒 ✓）
 *  ★ 返回 ✗ 1 = 备份成了（★ 可以安全升级 ✓）✗ 0 = 没成（★ 调用者【要报警】✓）
 *  ⚠️ ★★ 【不成功也要【如实上报】✗ 不能"静默地不带备份就升级"】✓✓ */
uint8_t Golden_SaveCurrent(void);

/* ★★★ 收到 `B` ✗ 清备份 + 把当前版本记成黑名单 ✓ */
void    Golden_ClearBackup(void);

/* ★★★★ 收到 `R` ✗ 请求回退：★ 置标志 + 软复位 ✓（★ 真正的恢复由 Boot 做 ✓）*/
void    Golden_RequestRollback(void);

/* ★ 当前运行镜像的 CRC（★ 和备份头里那个【必须同一套算法】✓）*/
uint16_t Golden_ImageCrc(void);

/* ★★ 备份状态（★ 只给人性化打印用 ✓）
 *  0 = 无备份 ✗ 1 = 有备份且与当前版本一致 ✗ 2 = 有备份但是别的版本 ✓ */
uint8_t Golden_BackupState(void);

#endif
