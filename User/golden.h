#ifndef __GOLDEN_H
#define __GOLDEN_H

#include "stm32f10x.h"

/*==============================================================================
 *  ★ 金副本（Golden Copy）—— 版本备份与回退（2026-10-14 建）
 *
 *  ★ 它解决什么：
 *    · App 坏了 / 卡死了，现在只有两条路：
 *      · 进 Bootloader（按键自救）→ 但还是需要一台 PC + 一个固件
 *      · 或者 拆下来用探针重烧
 *    · 有金副本之后，Boot 能自己把上一版装回来
 *      → "任意时刻都能自愈"
 *
 *  ★ 设计的灵魂："什么时候算一个好版本"
 *    ★ 如果用"永远跟着最新版本走"→ 升级到坏版本，备份立刻被覆盖
 *      回退就无从谈起
 *    → 所以本模块的规则只有四条：
 *    
 *    ① 槽空的 → 慢慢静默地填上当前这一版
 *    ② 槽已有内容 → 一个字节都不动（它代表"上一版"）
 *    ③ 要升级了 → 把当前正在跑的这一版写进去（覆盖）
 *    ④ PC 发 B → 清空 + 把当前版本的 CRC 记成黑名单
 *    
 *    ★ ①② 分开是关键：
 *      · 后台填充只负责"从无到有"
 *      · "从旧换新"只能由升级流程显式做
 *（因为只有升级那一刻，我们确定旧版本是好版本）
 *
 *  ★ 为什么第 ④ 条要"记黑名单"，光清空不够：
 *    · 只清空→ App 还在跑，下一拍它又把自己慢慢填回去了
 *    · 记下"这一版的 CRC"，规则改成
 *      槽空 且 我的 CRC ≠ 黑名单 → 才自动填
 *    → 效果：
 *      · 这一版（有 bug 的那个）永远不会被自动备份
 *      · 而你烧进好版本后（CRC 不同），它自己就会填上
 *
 *  ★ 一个"和 Bootloader 同源"的技巧：
 *    ★ 备份的头（magic/size/crc）最后才写
 *    → 传到一半掉电，头没写，这份备份天然无效
 *    → 下次开机看到"没有有效头"，从头重传
 *（和"先擦第 0 页，最后写回"是完全同一个思想）
 *
 *  ★ W25Q64 布局（按 64KB 块对齐，因为那是擦除单位）：
 *    
 *    0x000000 ~ 0x000FFF 4KB 头= [64B 头][其余留空]
 *                                ↑ 审计 G8：让它独占一个扇区
 *    0x001000 ~ 0x01CFFF 112KB 镜像（与 App 区等长
 *                                 ★ 跨 2 个 64KB 块 ⇒ 擦两块）
 *    0x020000 ~ 0x020FFF 4KB 元数据= 黑名单等（极少写）
 *    0x030000 ~ 0x030FFF 4KB 掉卡缓存·数据指针页
 *    0x031000 ~ 0x7A0FFF ~7.6MB 掉卡缓存·数据槽（7616 × 1024 B）
 *    0x7A1000 ~ 0x7A1FFF 4KB 掉卡缓存·事件指针页
 *    0x7A2000 ~ 0x7DDFFF 240KB 掉卡缓存·事件槽（960 × 256 B）
 *    0x7FF000 ~ 0x7FFFFF 4KB 自检扇区（已经在用）
 *    
 *    ★ 2026-10-19 补全（这张图原来又错又缺）：
 *      · 镜像尺寸还写着 56KB，那是 C8T6 时代的数（现在 112KB）
 *      · 而掉卡缓存那 7.6MB（占 W25 的 95%）
 *        在这张"总布局图"里一个字都没有
 *      ⇒ 现在一并补齐，免得以后有人以为 0x030000 之后是空的
 *      ⚠️ 另外记一笔潜伏冲突：W25Q64.h 里
 *        W25_ADDR_HISTORY = 0x010000 正压在镜像的第二块上
 *（目前全工程无人使用 ⇒ 没事
 *          ★ 但谁日后照那个宏去实现"历史版本"，就会和镜像互毁
 *    ★ 为什么镜像要退到 0x001000（审计 G8）：
 *      · 原方案把镜像放在 0x000100，和头同一个 4KB 扇区
 *      · 于是"清备份"时 EraseSector(0x000000)
 *        会连带擦掉镜像的头 3.9KB（正是向量表那段）
 *      · 现在这样，头独占 0x000~0xFFF，镜像从 0x1000 起
 *        → "清头"和"毁镜像"在物理上解耦
 *（而整体擦除仍然是一个 64KB 块，不用多擦一次）
 *
 *  ★ 分工（关键收益，见下）：
 *    · App（本模块），干所有"写"的活
 *（后台填充 / 升级前写 / 清 / 黑名单）
 *    · Boot，只"读 + 恢复"，永远不写 W25Q64
 *    → Boot 只加 ~1KB，8KB 里余 1,844 B守得住
 *============================================================================*/

/* ---- 镜像位置（必须和 Boot\boot_config.h 一致）-------------------
 *  ⚠️ 这两个值Boot 和 App 各有一份
 *    改一边必须改另一边，否则 Boot 恢复时会对不上地址 */
#define GOLDEN_APP_BASE      0x08004000u
/* ★ 2026-11-07 改：App 缩到 108KB，末尾 4KB 做参数区
 *   · 108 × 1024 = 110592，正好是 App 的新分区长度（0x1B000）
 *   ★ 必须和 Boot\boot_config.h 的 APP_SIZE 严格一致
 *     因为 Boot 校验备份时的判据是「magic == "GOLD" 且 size == APP_SIZE」
 *（见 Boot\boot_golden.h:45）
 *   ★ 不一致的后果：App 写 108KB，Boot 认 112KB
 *      → 备份被判为无效，回退功能静默失效，而且是"看起来正常"的那种失效 */
#define GOLDEN_APP_SIZE      (108u * 1024u)          /* ★ = 110592 */

/* ---- W25Q64 里的地址（见上面的布局图）-------------------------------- */
#define GOLDEN_ADDR_HDR      0x000000u              /* ★ 头（magic 最后写，独占一扇区） */
#define GOLDEN_ADDR_IMG      0x001000u              /* ★ 镜像（审计 G8：与头分扇区） */
#define GOLDEN_ADDR_META     0x020000u              /* ★ 元数据扇区。 */

#define GOLDEN_IMG_OFFSET    0x001000u              /* ★ 镜像在块内的偏移。 */
#define GOLDEN_BLOCK_SIZE    0x10000u               /* ★ 64KB。 */

/* ---- 魔数（不用简单的 1，理由同 boot_flag.h）------------------------ */
#define GOLDEN_HDR_MAGIC     0x474F4C44u            /* ★ "GOLD"。 */
#define GOLDEN_META_MAGIC    0x4D455441u            /* ★ "META"。 */
#define GOLDEN_CRC_NONE      0xFFFFu                /* ★ "没有黑名单"。 */

/* ---- 后台填充的速率（用户定，每 50ms 一页）------------------------
 *  ★ 一整份 112KB = 448 页（每页 256 B）
 *    → 448 × 50ms ≈ 22 秒
 *  ★ CPU 占用：每页软件 SPI 约 1.4ms
 *    → 1.4ms / 50ms ≈ 2.8%，仍然"静默"
 *  ⚠️ 2026-10-19 修正：原来这段写每 500ms 一页 / 219 页 / 110 秒
 *    · 219 那个数从来就没对过（112KB/256B = 448）
 *    · 而 500ms 也是旧值，现在的宏是
 *      GOLDEN_PAGE_INTERVAL_MS = 50 
 *  ★ 为什么不用更慢：太慢的话
 *    第一次上电后很久都没有备份可用，那段时间等于没有保护
 *  ★ 而且它是低优先级任务
 *    采集任务会抢占它，不会拖慢数据链 */
/* ★ 2026-10-18 改：500 → 50（用户拍板 B）
 *
 *  ★ 为什么改：
 *    · 这个常数原来只在 Golden_WriteAll(slow=1) 里用
 *      而那个分支是死代码，唯一调用点传的是 0
 *    · 所以"每页 500ms"从来没有生效过
 *      实际行为是：后台任务一页接一页地连写
 *      448 页 ⇒ 约 0.6 秒（算上两次 64KB 块擦最坏约 4 秒）
 *
 *  ★ 为什么这很危险：
 *    · GOLD/Task_SD 都是优先级 1，同级轮转
 *    · 那 0.6~4 秒里 task_SD 拿不到 CPU⇒ 落盘被推迟
 *    · 而乒乓缓冲只有 2 块（≈1.8 秒数据）
 *      ⇒ 超过就一定开始 no_buf 丢数据
 *（2026-10-18 实测到的 # LOST,...,106,no_buf 就是这类）
 *
 *  ★ 为什么选 50ms 而不是 500ms：
 *    · 50ms/页 ⇒ 448 × 50ms ≈ 22 秒填满
 *      → 每页之间都让出 CPU ⇒ SD 拿到足够时间片
 *    · 500ms/页 要 224 秒，太慢：上电后很久没有备份可用
 *（那段时间等于没保护，正是本文件下面担心的）
 *
 *  ★ CPU 账（新）：每页 1.4ms / 50ms ≈ 2.8%，仍然是"静默后台"。 */
#define GOLDEN_PAGE_INTERVAL_MS   50u

/*==============================================================================
 *  ★ 2026-10-18 加：掉卡缓存 API（W25 归 golden 所有 ⇒ 实现也在这里）
 *
 *  ★ 为什么放在 golden.h 而不是新开文件：
 *    · s_w25_lock 是 golden.c 的 static，外面拿不到
 *    · 而加新的 .c 到工程要改 .uvprojx（本项目禁止手改工程文件）
 *
 *  ★ 分区（避开金副本 0x000000~0x01C040 与元数据 0x020000）
 *    · 2026-10-19 扩容（整夜实测推动）：
 *        数据指针页  0x030000   4 KB
 *        数据槽 0x031000 ~ 0x7A1000 7616 × 1024 B = 7.6 MB（旧 2048）
 *        事件指针页 0x7A1000 4 KB（从 0x240000 挪来）
 *        事件槽      0x7A2000 ~ 0x7DE000   960 × 256 B
 *        自检扇区 0x7FF000 4 KB（绝不许碰）
 *    · 容量：7616 批 × 5 条/批 = 38,080 条 ≈ 63 分钟（旧版 20 分钟）
 *      ★ 2026-11-05 更正：原来写"6 条/批 ≈ 76 分钟"，而实测每批 5 条
 *        （512B ÷ 87B/条 = 5.9 ⇒ 装到第 6 条就超），容量按 5 条算。
 *    · 满了环形覆盖最旧的，不再"满了就停"
 *（旧行为：开机 21 分钟满 ⇒ 之后 8 小时全丢）
 *
 *  ★ v1 策略（早已改成环形覆盖，这一节 2026-10-20 更正）：
 *    · ~~满了就停~~ ⇒ 现在是"满了丢最旧的"（保最近的，记在 rsv 里）
 *    · 全部回写完成后清零指针⇒ 下次断卡从头写（写前按扇区擦）
 *  ★ 回写顺序：调用者先 Peek、写卡成功后再 Pop，保证不丢
 *  ★ 2026-10-20 G5：指针不再是一个 4 KB 页，改成 A/B 两个扇区的追加日志
 *    · 擦除率从"每批 2 次"降到"每 256 条 1 次"
 *    · 掉电最多丢 1 批（原来的 45 ms 擦除窗口会丢 76 分钟）
 *============================================================================*/
uint8_t  DropCache_Init(void);                              /* 上电扫两条指针日志（无 W25 返回 0）*/
uint8_t  DropCache_PutBatch(const uint8_t *p, uint16_t len);/* 存一批（512B），1=成功 */
uint8_t  DropCache_PeekBatch(uint8_t *dst, uint16_t *len);  /* 读最早一批（不推进）。 */
void     DropCache_PopBatch(void);                          /* 回写成功后才推进。 */
uint16_t DropCache_PendingBatches(void);                    /* 还有几批没回写。 */
/* ★ 2026-10-19 加：环形溢出次数（满了以后丢了多少项）
 *   · 不动 ⇒ 缓存没满
 *   · 在涨 ⇒ 缓存满，正在丢最旧的数据 */
uint16_t DropCache_OverflowCount(void);
/* ★ 2026-10-20 加（G5 的证据）：指针日志扇区擦除次数（上电后累计）
 *   · 断卡跑几分钟 ⇒ 应该只涨 0~1（按秒涨 = 没走日志路径） */
uint16_t DropCache_HdrErases(void);
uint16_t DropCache_EvtHdrErases(void);
uint8_t  DropCache_PutEvent(const char *line);              /* 存一条事件行。 */
uint8_t  DropCache_PeekEvent(char *dst, uint16_t sz);       /* 读最早一条（不推进）。 */
void     DropCache_PopEvent(void);
uint16_t DropCache_PendingEvents(void);
uint32_t DropCache_LockWaitMaxMs(void);                     /* W25 锁：最长一次等锁（ms）*/
uint32_t DropCache_LockWaitSlowCnt(void);                   /* W25 锁：等锁 >= 100ms 的次数 */

/*==============================================================================
 *  ★ 对外接口
 *============================================================================*/

/* ★ 初始化：建任务前调一次，读元数据/算自己的 CRC
 *  ★ 返回 1 = W25Q64 在位（不在位就整个功能自动静默关闭） */
uint8_t Golden_Init(void);

/* ★ 后台填充任务（低优先级，慢慢传）
 *  ★ 逻辑：
 *    · 已经备份过了（CRC 一致）→ 直接睡
 *    · 被列入黑名单 → 睡
 *    · 否则 → 擦块 → 逐页传 → 最后写头→ 睡 */
void    Golden_Task(void);

/* ★ 升级前把当前这一版写进备份（同步，约 2~3 秒）
 *  ★ 返回，1 = 备份成了（可以安全升级），0 = 没成（调用者要报警）
 *  ⚠️ 不成功也要如实上报，不能"静默地不带备份就升级" */
uint8_t Golden_SaveCurrent(void);

/* ★ 收到 B，清备份 + 把当前版本记成黑名单。 */
void    Golden_ClearBackup(void);

/* ★ 收到 R，请求回退：置标志 + 软复位（真正的恢复由 Boot 做） */
void    Golden_RequestRollback(void);

/* ★ 当前运行镜像的 CRC（和备份头里那个必须同一套算法） */
uint16_t Golden_ImageCrc(void);

/* ★ 备份状态（只给人性化打印用）
 *  0 = 无备份，1 = 有备份且与当前版本一致，2 = 有备份但是别的版本。 */
uint8_t Golden_BackupState(void);

#endif
