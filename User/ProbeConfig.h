#define TEST_SD_ON          1   /* SD 初始化 + 读扇区 0 验 MBR（换板/换卡后才开） */

/*---------------- 无人值守：整只蜂鸣器静音（2026-11-09 加）---------------- */
#define TEST_MUTE_BUZZ      0   /* 1 = App 启动后调 Buzz_Silence(1)，按键与 SD 报警都不响
                                 *   ★ 只在"拔卡跑一整夜"这类实验里开
                                 *     平时必须 0：SD 故障那 2.5Hz 报警是无人值守唯一的提示
                                 *   ⚠️ 开了它，屏上 E:03 / 串口 sd_err 都还在，只是没声音 */

/*---------------- 掉卡缓存：每批几条的诊断（2026-11-10 加）---------------- */
