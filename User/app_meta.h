#ifndef __APP_META_H
#define __APP_META_H

#include <stdint.h>

/*==============================================================================
 *  ★ 镜像元数据（U5 防回滚，2026-11-07）
 *
 *  ★ 放在哪：没有固定地址，跟着 .rodata 走
 *    · 原本想用 at(0x08004200) 钉在向量表之后，实测会让 App 静默
 *      （limitations 第 33 条）⇒ 改成让 Boot 在暂存镜像里扫 "ATEM"
 *    · 所以下面的 APP_META_ADDR 只是"大概在哪"的说明，代码里别按它取
 *    · 代价：Boot 每次升级要多扫一遍镜像（约 1.7 秒）
 *
 *  ★ 为什么写进镜像而不是加一条串口命令：
 *    · 版本跟着镜像走，PC 端一行都不用改
 *    · 也不会出现"声明的版本和实际镜像不符"这种自欺
 *    · Boot 从 W25 暂存区就能读到，不用等装完
 *
 *  ★ 规矩：version 只增不减；每次发布改大，否则会被 Boot 拒绝
 *============================================================================*/

#define APP_META_ADDR     0x08004200u      /* ★ 仅说明用，代码里不按它取 */
#define APP_META_MAGIC    0x4D455441u      /* ★ "ATEM" 小端 */

typedef struct
{
	uint32_t magic;       /* ★ APP_META_MAGIC */
	uint32_t version;     /* ★ 单调递增，防回滚判据 */
	uint32_t build;       /* ★ 构建标识（日期数字），只给人看 */
	uint32_t rsv;
} AppMeta_t;

#endif
