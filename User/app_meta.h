#ifndef __APP_META_H
#define __APP_META_H

#include <stdint.h>

/*==============================================================================
 *  ★ 镜像元数据（U5 防回滚，2026-11-07）
 *
 *  ★ 放在哪：App 区起始 + 0x200（向量表之后、代码之前），固定绝对地址
 *    · 必须固定：Boot 按"镜像 + 偏移"直接取，不能依赖符号表
 *    · 0x200 之前是向量表（最多 128 个入口），不会撞
 *    · 代价：每次编译多花约 270 字节空隙 —— 换"Boot 能独立读"，值
 *
 *  ★ 为什么写进镜像而不是加一条串口命令：
 *    · 版本跟着镜像走，PC 端一行都不用改
 *    · 也不会出现"声明的版本和实际镜像不符"这种自欺
 *    · Boot 从 W25 暂存区就能读到，不用等装完
 *
 *  ★ 规矩：version 只增不减；每次发布改大，否则会被 Boot 拒绝
 *============================================================================*/

#define APP_META_ADDR     0x08004200u
#define APP_META_MAGIC    0x4D455441u      /* ★ "ATEM" 小端 */

typedef struct
{
	uint32_t magic;       /* ★ APP_META_MAGIC */
	uint32_t version;     /* ★ 单调递增，防回滚判据 */
	uint32_t build;       /* ★ 构建标识（日期数字），只给人看 */
	uint32_t rsv;
} AppMeta_t;

#endif
