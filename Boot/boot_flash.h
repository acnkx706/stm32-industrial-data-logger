#ifndef __BOOT_FLASH_H
#define __BOOT_FLASH_H

#include <stdint.h>
#include "boot_config.h"

/*==============================================================================
 *  ★★★★ Bootloader 的 Flash 擦 / 写（2026-10-13 建 ✓）★ 第三步
 *
 *  ★ 为什么【必须单独包一层**✗✓（★ 不能直接调库函数 ✓）：
 *    · ★ ① 【擦写期间【必须关中断】**✗✓
 *      → 【F103 擦写 Flash 时【CPU 取不到指令】✗ 包括【取中断向量】】✓
 *      → ★★ 而这期间【串口 ISR 就在 Flash 里】✗
 *        → 【一来中断【直接 HardFault】】✓✓
 *      → ★★★ 【现象是"升级到一半突然死机"✗ 而且【日志都看不全】】✓✓
 *      → ★★★★ 【这是【最容易忘 ✗ 后果最狠】的一条】✓✓
 *      ⚠️ 代价 ✗：关中断期间【收不到串口字节】✗
 *        → 【所以 PC 侧【必须停等】✗ 不许盲发】✓✓（见 PC 工具 ✓）
 *    · ★★ ② 【每次操作后【必须查状态】】✗✓
 *      → 【Flash 操作失败【不报错 ✗ 只是数据没写进去】】✓
 *      → ★★★ 不查 = 静默失败 = 【最后跳进一个坏 App】✓✓
 *    · ★★★ ③ 【写完【必须回读比对】】✗✓
 *      → ★★ 【这是【唯一能证明"Flash 里真的是那份数据"】的办法】✓✓
 *
 *  ★★ 返回码（★ 0 = OK ✗ 故意【不返回 0/1 两态】✓）
 *    · ★ 为什么要分这么细 ✗：★【出错时【串口要能说清【错在哪】】】✓
 *      → 【不然只能干看着 "FAIL"】✓✓
 *============================================================================*/

#define BOOTFLASH_OK            0u   /* ★ 成功 ✓ */

/* ★ 擦除失败族（★ 1~2 ✓）*/
#define BOOTFLASH_ERR_ERASE     1u   /* ★ `FLASH_ErasePage` 没回 COMPLETE ✓ */
#define BOOTFLASH_ERR_ERASE_WRP 2u   /* ★★ 写保护（★ 开了读保护就会这样 ✓）*/

/* ★★ 写入失败族（★ 3~4 ✓）*/
#define BOOTFLASH_ERR_WRITE     3u   /* ★ 编程没回 COMPLETE ✗ 或置了 PGERR ✓ */
#define BOOTFLASH_ERR_WRITE_WRP 4u   /* ★★ 写保护 ✓ */

/* ★★★ 回读失败（★ 5 ✓）*/
#define BOOTFLASH_ERR_VERIFY    5u   /* ★★ 写进去了 ✗ 但【读出来不一样】✓ */

/* ★★★★ 擦除一个 Flash 页（★ `addr` 必须是【页首地址 ✗ 1KB 对齐】✓）
 *
 *  ★ 页大小 = **1024 字节** ✗（★ 中容量 C8T6 固定 1KB 一页 ✓）
 *  ★★ 擦除【只能整页**✗ 没有"擦 16 字节"这种东西 ✓
 *  ★★★ 擦完那一页【全是 0xFF】✓（★ 空 Flash = 全 1 ✓）
 *  ★★★★ 擦除耗时 ✗：★ **典型 20ms ✗ 最大 40ms** ✓（★ 这段【PC 必须在等】✓）*/
uint8_t BootFlash_ErasePage(uint32_t addr);

/* ★★★★ 写满一页（★ 固定 `BOOT_FLASH_PAGE_SIZE` = 1024 字节 ✓）
 *
 *  ★ 为什么【写【整页】✗ 而不是"写 n 字节"✓：
 *    · ★ 我们【本来就【攒满一页才写**✗（★ 见 boot_upgrade.c 的页缓冲 ✓）
 *    · ★★ 【而且【最后一页【要补 0xFF 凑满】】✗（★ 补在缓冲里 ✓）
 *    → 【所以【接口上【只需要"写一页"】✗ 少一个参数 = 少一个出错点】✓✓
 *
 *  ★★ `buf` 必须【已经补好 0xFF ✗ 长度正好 1024】✓
 *  ★★★ 内部【自动关中断 + 查状态 ✗ 但不回读】✓（★ 回读用下面那个 ✓）*/
uint8_t BootFlash_WritePage(uint32_t addr, const uint8_t *buf);

/* ★★★★ 回读比对（★ 写完【立刻】调 ✗ 才算闭环 ✓）
 *  ★ 返回 BOOTFLASH_OK = 【Flash 里和 buf 一字不差】✓
 *  ★★ 【不需要关中断 ✗ 读 Flash 不占写总线】✓ */
uint8_t BootFlash_VerifyPage(uint32_t addr, const uint8_t *buf);

#endif
