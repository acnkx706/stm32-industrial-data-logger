#ifndef __BOOT_JUMP_H
#define __BOOT_JUMP_H

#include <stdint.h>

/*==============================================================================
 *  ★★★★ 跳转与 App 有效性检查（2026-10-13 建 ✓）
 *
 *  ★ 这两个函数是【整个 Bootloader 的核心】✗✓ ——
 *    · 一个【判断"能不能跳"】✓
 *    · 一个【真的跳过去】✓✓
 *
 *  ★★ 设计参考 ✗：`stm32-bootloader-master`（★ Akos Pasztor ✓）
 *    它的 `BootloaderCheckForApplication()` / `BootloaderJumpToApplication()`
 *    就是这个思路 ✗ 我照搬了它的【两个便宜判据】✓✓
 *============================================================================*/

/**
 * @brief  检查 App 区里是否有一个【看起来有效】的应用程序。
 *
 * ★ 判据只有两个 ✗（★ 都是"读两个字"的便宜操作 ✓）：
 *   ① App 首字 = 初始栈顶指针 ✗ 必须落在 RAM 范围内 ✓
 *   ② App 第二个字 = 复位向量 ✗ 必须落在 App 区内 ✗
 *      且不是 0xFFFFFFFF（★ 空 Flash / 擦过后全是 1 ✓）
 *
 * ★★ 为什么【这两个判据就够用】✗：
 *   · ★ 空 Flash ✗ → 【第一个字是 0xFFFFFFFF ✗ 不在 RAM 内 → 挡掉】✓
 *   · ★★ 写到一半的固件 ✗ → 【复位向量多半不在 App 区内 → 挡掉】✓
 *   · ★★★ 栈指针被写乱 ✗ → 【不在 RAM 内 → 挡掉】✓✓
 *
 * @return 1 = 有有效 App ✓；0 = 没有（★ 调用者应停在升级模式 ✓）
 */
uint8_t Boot_IsAppValid(void);

/**
 * @brief  跳到 App 区去执行。
 *
 * ★ 标准五步（★ 顺序很重要 ✗ 不能换 ✓）：
 *   ① 【关掉所有中断 + 清掉挂起】✗
 *      —— ★ 不关的话 ✗ 【Bootloader 里开过的中断】会在跳过去之后
 *         用【旧的向量表】触发 ✗ → 【直接 HardFault】✓✓
 *   ② 【关掉 SysTick】✗（★ 它是内核外设 ✗ 会继续跑 ✓）
 *   ③ 【把向量表搬到 App 那边】✗（★ `SCB->VTOR = APP_BASE` ✓）
 *      —— ★★ 这是【Cortex-M3 的硬件功能 ✗ 也是【为什么能这么做】的原因】✓✓
 *   ④ 【把栈指针设成 App 的首字】✗
 *   ⑤ 【跳到 App 的复位向量】✗
 *
 * ★★ 本函数【不会返回】✗ —— 除非 App 的复位向量是错的（★ 那时会跑飞 ✓）
 *    所以【调用前必须先用 Boot_IsAppValid() 确认】✓✓
 */
void Boot_JumpToApp(void);

#endif
