/* ---- Flash 分区 ---------------------------------------------------------- */

/* ★ Bootloader 区（★ 从 0x08000000 开始 ✗ 芯片复位后【必然】从这里跑 ✓）
 *
 *  ★★ 2026-10-13 调整 ✗：★ 4KB → **8KB** ✗✓
 *    · ★ 原因：★ 实测【4KB 装不下】✗ —— 链接器报
 *      `L6406E: No space in execution regions` ✓
 *    · ★★ 体积账（★ 4KB 编译时量到的 ✓）：
 *      · `printfa.o` ✗ —— ★ 格式化输出（★ `%lu` / `%08X` 拉进来的 ✓）
 *      · `uldiv.o` / `uidiv.o` ✗ —— ★ 除法 ✓
 *      · `dfixul.o` / `llshl.o` / `llsshr.o` ✗ —— ★ 定点 + 64 位移位 ✓
 *      · 加上各驱动 + 启动代码 + 中断向量 ✗ → ★【5.4KB】✗✓
 *    · ★★★ 现在【Code = 5,484 B】✗ 8KB【余量 2.7KB】✓✓
 *    · ★★★★ 以后【想省回 4KB**✗ → 【不用 `printf` ✗ 自己写极简输出】✓
 *      （★ 能砍掉上面那 4 类库 ✗ 约 2~3KB ✓）*/
#define BOOT_BASE        0x08000000u
#define BOOT_SIZE        (8u * 1024u)        /* ★ 8KB ✗ 实测用 5.4KB ✓ */

/* ★★ App 区（★ 紧接在 Bootloader 后面 ✗ 必须【页对齐】✓）
 *   ★ 为什么是 0x08002000 ✗：★ Boot = 8KB = 0x2000 ✗ 8 个 Flash 页 ✓
 *   ★★ 为什么【必须页对齐】✗：★ 擦除【只能整页擦 ✗ 1KB 一页】✓✓
 *   ★★★ 2026-10-13 调整 ✗：★ 0x08001000 → **0x08002000**（★ 跟着 Boot 变 ✓）*/
#define APP_BASE         0x08002000u
#define APP_SIZE         (56u * 1024u)       /* ★ 56KB ✗ 64 - 8 ✓ */
#define APP_END          (APP_BASE + APP_SIZE)

/* ★ 芯片总容量（★ 只作参考 ✗ 实际可用范围由【链接器】管 ✓）
 *  ⚠️ 2026-10-13 修正 ✗：★ 原来这里叫 `FLASH_BASE` ✗
 *    结果和 `stm32f10x.h` 里的同名宏【撞车】✗✓
 *    · ★ 那个 `FLASH_BASE` 是【外设寄存器基地址】（★ 完全不同的东西 ✓）
 *    · ★★ 编译器报 `incompatible redefinition` ✓
 *  → ★★★ 所以【加了 `MCU_` 前缀 ✗ 避开库里的名字】✓✓
 *  ★★★★ 教训：★【自己起的宏名 ✗ 也要防撞 ✗ 尤其是库文件里有的】✓ */
#define MCU_FLASH_BASE   0x08000000u
#define MCU_FLASH_SIZE   (64u * 1024u)
#define MCU_FLASH_END    (MCU_FLASH_BASE + MCU_FLASH_SIZE)

/* ---- RAM（★ 用来判断"栈顶指针是否合法" ✓）------------------------------- */

/* ★★ STM32F103C8T6 = 20KB SRAM ✗ 起始 0x20000000 ✓ */
#define RAM_BASE         0x20000000u
#define RAM_SIZE         (20u * 1024u)
#define RAM_END          (RAM_BASE + RAM_SIZE)

/* ---- Flash 页（★ 擦除的【最小单位 ✗ 也是【唯一】单位】✓）----------------- */

/* ★★★★ STM32F103C8T6（★ 中容量 md ✓）的 Flash 页 = **1KB** ✓
 *   · ★ 【擦除【只能整页**✗ 没有"擦 16 字节 / 擦 512 字节"这种东西】✓
 *   · ★★ 所以【App 区（56KB）= 56 页】✗
 *     → 【升级时【一页一页地"擦 → 写 → 回读"】✓✓
 *   · ★★★ 【页号 → 地址】的换算【全靠它**✗ 所以【必须只有一份】✓ */
#define BOOT_FLASH_PAGE_SIZE  1024u

/* ---- 看门狗（★ IWDG ✗ 2026-10-13 加 ✓）---------------------------------- */

/* ★★★★ 为什么【Bootloader 【必须】喂狗**✗✓
 *         —— ★ 这是【本次审查【最致命】的一条 ✗ 不修它【后面什么都测不了】✓
 *
 *   · ★ 实测事实 ✗：★ App 在 `main.c` 里调过 `WD_Init()` ✗
 *     【超时 = 6.55 秒】（★ 预分频 64 ✗ 重装 4095 ✓）
 *   · ★★ 【IWDG 一旦启动 ✗【软复位【不会】停它】】✗✓!!
 *     → ★【只有【上电复位 / NRST 引脚复位】才停】✓
 *     → ★★ 而【复位后【PR / RLR 保持 ✗ 计数器【继续跑】】✓✓
 *   · ★★★ 而【App 请求升级【恰恰就是软复位**✗（★ `NVIC_SystemReset()` ✓）
 *     → 【狗还在跑 ✗ 而 Bootloader 是【裸机忙等 ✗ 没人喂】】✗✓
 *     → ★★★★ 【6.55 秒后咬 → 复位 → 又进 Bootloader → 无限循环】✓✓
 *       （★ 现象是【"板子一直在重启"✗ 而【传 56KB 要 10~15 秒 ✗ 根本传不完】】✓）
 *
 *   ★★ 为什么【连"App 无效"那条路也要喂**✗：
 *     · ★ 原来那条路是 `for(;;){}` 【真停住】✓
 *     · ★★ 但【狗一咬 ✗ 它就【每 6.55 秒重启一次】】✓
 *       → 【看起来像"停住"✗ 其实【一直在重启】】✓✓
 *
 *   ★★★ 为什么【直接写寄存器 ✗ 不用 `IWDG_ReloadCounter()`】✗：
 *     · ★ 那个函数在 `Library\stm32f10x_iwdg.c` 里 ✓
 *     · ★★ 而【那个文件【没被加进 Boot 工程】】✗（★ 也用不着整个库 ✓）
 *     · ★★★ 【喂狗【就是往 KR 写一个常数 ✗ 一条 store 而已】】✓
 *       → 【没必要为它【加一个源文件 ✗ 还多一份工程配置要维护】】✓✓
 *
 *   ★★★★ 密钥说明 ✗：★ `0xAAAA` = 【重装计数器】✓
 *     · ⚠️ 【别和 `0xCCCC` 搞混 ✗ 那是"启动 IWDG"】✗✓
 *     · ★★ 【没启动时写 `0xAAAA` 【是无害的 ✗ 不会把它启动起来】】✓
 *       → 【所以【无条件喂 ✗ 不需要先判断"狗开着没"】】✓✓ */
#define IWDG_KR_RELOAD        0xAAAAu

#define BOOT_FEED_IWDG()      do { IWDG->KR = IWDG_KR_RELOAD; } while (0)

/* ★★★★ 看门狗"现场取证"开关（★ 2026-10-13 加 ✗ 结论拿到后可以关 ✓）
 *
 *  ★★ 为什么要它 ✗ —— ★ 因为【实测和评审文档对不上】✗✓：
 *    · ★ 评审说：【IWDG 软复位后不停 ✗ 会每 6.55 秒打断升级】✓
 *    · ★★ 而【实测**（★ 2026-10-13 深夜 ✗ 旧 Bootloader ✓）✗：
 *      · 【App 跑着 → 发 `U` → 软复位 → 进旧 Boot 升级模式】✓
 *      · 【然后【静置 22 秒**✗ `=== BOOT ===` 【只出现 1 次 ✗ 一次复位都没有】】✓✓
 *    → ★★★ 【所以【"坑 1"在这块板上【没有复现】】✓
 *      但【原因】是什么 ✗ 【只能靠读寄存器钉死】✓✓
 *
 *  ★★★ 三个寄存器能分辨什么 ✗（★ 开机第一件事就打 ✓）：
 *    · ★ **PR** ✗ 预分频 ✗ 【复位默认 0 ✗ App 设成 4（/64）】✓
 *      → ★★ 【它是最关键的判据**✗：
 *        · 【读到 **4** ✗ = 寄存器【活过了软复位】】
 *          → 【那么"没复位"只能是【计数没在跑】】✓
 *        · 【读到 **0** ✗ = 【整个 IWDG 外设被软复位清了】】
 *          → 【那"软复位会停狗"就【解释得干干净净】】✓✓
 *    · ★★ **RLR** ✗ 重装值 ✗ ★ 可惜【复位默认 0xFFF = 4095 ✗ 和 App 设的一模一样】✗
 *      → 【★ 它【不能区分**✗ 只能当旁证】✓✓
 *    · ★★★ **SR** ✗ 状态 ✗ 只有 PVU/RVU/WVU 三个"更新中"标志 ✓
 *
 *  ★★★★ 注意 ✗：★ 这只在"**软复位进来的**"那一次才有意义 ✓
 *    · ★ 上电复位（★ 拔电重上 ✓）进来的那次 ✗ PR 本来就会是 0 ✓
 *      → 【所以【看日志时【要配合"这次是怎么进来的"一起读】】✓✓ */
#define BOOT_IWDG_PROBE       1

/* ---- 判据宏（★ 让 boot_jump.c 读起来更清楚 ✓）--------------------------- */

/* ★ App 的首字 = 【初始栈顶指针】✗ 必须落在 RAM 里 ✓ */
#define BOOT_IS_SP_VALID(sp)   ( ((sp) >= RAM_BASE) && ((sp) <= RAM_END) )

/* ★★ App 的第二个字 = 【复位向量（＝第一条指令地址）】✗
 *   必须落在 App 区内 ✗ 而且不能是 0xFFFFFFFF（★ 空 Flash 被擦后全是 1 ✓）*/
#define BOOT_IS_PC_VALID(pc)   ( ((pc) >= APP_BASE) && ((pc) < APP_END) && \
                                 ((pc) != 0xFFFFFFFFu) )

