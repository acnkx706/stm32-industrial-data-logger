#ifndef __BOOT_FLAG_H
#define __BOOT_FLAG_H

#include <stdint.h>

/*==============================================================================
 *  ★ 升级请求标志（2026-10-13 建）—— 存在备份寄存器里
 *
 *  ★ 为什么用 BKP（备份寄存器）：
 *    · 它属于备份域
 *    · 而软复位不会动备份域 → 标志能活下来
 *    · 这正是"App 请求升级 → 软复位 → Bootloader 读到"的基础
 *
 *  ★ 为什么不用 RAM：
 *    · RAM 在软复位后也保留—— 看起来能用
 *    · 但它会被栈 / 全局变量覆盖 —— 不可靠
 *    · 而BKP 没有任何代码会碰它
 *      只有显式读写才会变
 *
 *  ★ 寄存器选择极其重要：
 *    · BKP_DR2 ← 我们用这个
 *    · BKP_DR1 已经被 RTC 的魔数占用!!
 *      （MyRTC.c:21 → #define RTC_BKP_DR BKP_DR1）
 *    · 绝对不能用 DR1
 *      → 否则RTC 会以为"没配置过"，重新初始化，时间直接倒退
 *
 *  ★ 这个头文件App 和 Bootloader 各有一份
 *    · 两边必须一字不差（特别是寄存器和魔数）
 *    · 因为我们没有共享目录，改的时候两边一起改
 *============================================================================*/

/* ★ 用哪个备份寄存器（见上面"寄存器选择"） */
#define BOOT_FLAG_DR        BKP_DR2

/* ★ 魔数（为什么不用简单的 1）
 *   · 备份域没装 VBAT 时，上电可能是随机值
 *     （本板已装电池 ⇒ 读到的一般是上次的值，但仍按随机值防御）
 *   · 用魔数能避免误判：随机值几乎不可能正好是它
 *   · 0xA5C3 是随便挑的，只要两边一致就行。 */
#define BOOT_FLAG_MAGIC     0xA5C3u

/*==============================================================================
 *  ★ 回退请求标志（2026-10-14 加）—— 和升级标志一样存在备份寄存器里
 *
 *  ★ 为什么不复用 BOOT_FLAG_DR：
 *    · 升级标志的语义，"我要升级，请去收新固件"
 *    · 回退的语义，"我要回到备份，请去W25Q64 拿旧版本"
 *    · 两件事完全不同，混用一个寄存器必然打架
 *
 *  ★ 寄存器选择：BKP_DR1 被 RTC 魔数占用，BKP_DR2 是升级标志
 *    → 所以用 BKP_DR3
 *  ★ 魔数故意和升级的不一样（0x5C3A vs 0xA5C3）
 *    → 这样即使读错了寄存器，也不会误判成"要升级"
 *
 *  ⚠️ 本文件App 和 Bootloader 各有一份，必须一字不差
 *============================================================================*/
#define BOOT_ROLLBACK_DR     BKP_DR3
#define BOOT_ROLLBACK_MAGIC  0x5C3Au

/* ★ 2026-10-18 加（⑥ 用户拍板 A）：IWDG 回退已尝试次数
 *
 *  ★ 为什么要它：
 *    · 恢复判据⑤是"上次复位是 IWDG 咬的 ⇒ 认为 App 卡死 ⇒ 换回旧版"
 *    · 但它没有任何次数上限，会出三种坏情况：
 *      ① 偶发被狗咬（例：SD 卡顿 4 秒正好撞上）
 *         ⇒ 镜像明明好的，却被静默换回上一版
 *      ② 旧版也咬狗 ⇒ 每次开机擦写 108 KB 的循环
 *         （W25 每扇区 10 万次 ⇒ 加速磨损）
 *      ③ 而且没有"停下来等人"的机会
 *
 *  ★ 语义（拍板 A）：
 *    · 第 1 次 IWDG 复位 ⇒ 照旧自动回退（自愈优先）
 *    · 第 2 次（说明回退也没救回来）⇒ 不再擦写 ⇒ 停在升级模式等 PC
 *      （理由：回退都救不回 ⇒ 问题不在版本上⇒ 该人来看了）
 *
 *  ★ 寄存器选择：BKP_DR4 被低功耗方案预定了（主动睡眠标记）
 *    ⇒ 用 BKP_DR6（DR1/2/3/5 已占，DR4 预留）
 *
 *  ★ 掉电行为：没 VBAT ⇒ 掉电清零
 *    ★ 本板已装电池 ⇒ 这个计数会【跨断电保留】，
 *      所以"连续失败"的语义变成了"累计失败"（仍限幅到 3）*/
#define BOOT_IWDG_RETRY_DR   BKP_DR6


/* ★ 初始化：打开 PWR + BKP 时钟，并解锁备份域
 *   ★ 必须在任何 BKP 读写之前调用，否则读出来是 0，写了没效果 */
void BootFlag_Init(void);

/* ★ 读标志：返回 1 = 有升级请求；0 = 没有。 */
uint8_t BootFlag_IsUpgradeRequested(void);

/* ★ 清除请求（升级成功之后必须调，否则永远停在升级模式） */
void BootFlag_ClearUpgrade(void);

/* ★ 请求升级（App 侧用这个，Bootloader 用不上）
 *   ★ 注意：本函数只写标志，不会复位
 *     · 调用者要自己决定什么时候 NVIC_SystemReset() */
void BootFlag_RequestUpgrade(void);

/*==============================================================================
 *  ★ 回退请求（2026-10-14 加，G5 用）
 *
 *  ★ 语义："我要回到备份，请去 W25Q64 拿旧版本"
 *  ★ 和升级标志完全独立，用另一个寄存器 + 另一个魔数
 *    （理由见上面 BOOT_ROLLBACK_DR 的说明）
 *
 *  ★ 谁写它：App 侧 Golden_RequestRollback()（PC 发 R）
 *  ★ 谁清它：恢复成功之后，由 Boot 清
 *    ★ 为什么必须清：不清的话每次开机都以为"要回退"
 *      → 会反复恢复，而且每次都白等好几秒
 *============================================================================*/
uint8_t BootFlag_IsRollbackRequested(void);
void    BootFlag_ClearRollback(void);

/* ★ 2026-10-18 加：IWDG 回退次数（说明见上）。 */
uint8_t BootFlag_GetIwdgRetry(void);     /* 读已尝试次数（0 = 还没试过） */
void    BootFlag_IncIwdgRetry(void);     /* 每次决定"自动回退"前 +1。 */
void    BootFlag_ClearIwdgRetry(void);   /* 升级成功 / 决定停升级模式时清 0。 */

#endif
