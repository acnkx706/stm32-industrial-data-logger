#ifndef __BOOT_FLAG_H
#define __BOOT_FLAG_H

#include <stdint.h>

/*==============================================================================
 *  ★★★★ 升级请求标志（2026-10-13 建 ✓）—— 存在【备份寄存器】里 ✓
 *
 *  ★ 为什么用 BKP（备份寄存器）✗：
 *    · ★ 它【属于【备份域】】✗✓
 *    · ★★ 而【软复位【不会】动备份域】✗ → 【标志能活下来】✓✓
 *    · ★★★ 【这正是【"App 请求升级 → 软复位 → Bootloader 读到"】的基础】✓
 *
 *  ★★ 为什么【不用 RAM**✗：
 *    · ★ RAM 在软复位后【也保留】✓ —— 看起来能用 ✓
 *    · ★★ 但【它【会被栈 / 全局变量覆盖】】✗✓ —— 不可靠 ✓
 *    · ★★★ 而【BKP 【没有任何代码会碰它】✗
 *      只有【显式读写】才会变 ✓✓
 *
 *  ★★★ 寄存器选择【极其重要】✗：
 *    · ★ **`BKP_DR2`** ✗✓ ← 我们用这个 ✓
 *    · ★★ 【`BKP_DR1` 【已经被 RTC 的魔数占用】**✗✓!!
 *      （★ `MyRTC.c:21` → `#define RTC_BKP_DR  BKP_DR1` ✓）
 *    · ★★★ 【【绝对不能用 DR1】✗✓
 *      → 【否则【RTC 会以为"没配置过" ✗ 重新初始化 ✗ 时间直接倒退】】✓✓
 *
 *  ★★★★ 这个头文件【App 和 Bootloader 各有一份】✗✓
 *    · ★ 两边【必须一字不差】（★ 特别是【寄存器和魔数】✓）
 *    · ★★ 因为我们【没有共享目录】✗ 改的时候【两边一起改】✓✓
 *============================================================================*/

/* ★ 用哪个备份寄存器（★ 见上面"寄存器选择" ✓）*/
#define BOOT_FLAG_DR        BKP_DR2

/* ★★ 魔数（★ 为什么不用简单的 1 ✗✓）
 *   · ★ 【备份域【没装 VBAT 时 ✗ 上电可能是【随机值】】✓
 *   · ★★ 【用魔数【能避免误判】：★ 随机值【几乎不可能】正好是它】✓✓
 *   · ★★★ 【0xA5C3 是随便挑的 ✗ 只要【两边一致】就行】✓ */
#define BOOT_FLAG_MAGIC     0xA5C3u

/*==============================================================================
 *  ★★★★ 回退请求标志（★ 2026-10-14 加 ✓）—— 和升级标志一样存在备份寄存器里
 *
 *  ★ 为什么【不复用 `BOOT_FLAG_DR`**✗✓：
 *    · ★ 升级标志的语义 ✗【"我要【升级】✗ 请去【收新固件】"】✓
 *    · ★★ 回退的语义 ✗【"我要【回到备份】✗ 请去【W25Q64 拿旧版本】"】✓✓
 *    · ★★★ 【两件事【完全不同】✗ 混用一个寄存器【必然打架】】✓✓
 *
 *  ★★ 寄存器选择 ✗：★ `BKP_DR1` 被 RTC 魔数占用 ✗ `BKP_DR2` 是升级标志 ✓
 *    → ★★★ 【所以用 `BKP_DR3`】✓
 *  ★★★★ 魔数【故意和升级的不一样**✗（★ `0x5C3A` vs `0xA5C3` ✓）✗
 *    → ★【这样【即使读错了寄存器 ✗ 也【不会误判成"要升级"】】✓✓
 *
 *  ⚠️ ★★★ 本文件【App 和 Bootloader 各有一份】✗ 【必须一字不差】✓✓
 *============================================================================*/
#define BOOT_ROLLBACK_DR     BKP_DR3
#define BOOT_ROLLBACK_MAGIC  0x5C3Au

/* ★★★★ 2026-10-18 加（⑥ 用户拍板 A）：IWDG 回退【已尝试次数】✗✓
 *
 *  ★ 为什么要它 ✗：
 *    · 恢复判据⑤是"上次复位是 IWDG 咬的 ⇒ 认为 App 卡死 ⇒ 换回旧版"✓
 *    · ★★ 但它【没有任何次数上限】✗ 会出三种坏情况 ✓：
 *      ① 偶发被狗咬（例：SD 卡顿 4 秒正好撞上）
 *         ⇒ 镜像明明好的，却被【静默换回上一版】✓
 *      ② 旧版也咬狗 ⇒ 【每次开机擦写 112 KB】的循环 ✓
 *         （W25 每扇区 10 万次 ⇒ 加速磨损 ✓）
 *      ③ 而且【没有"停下来等人"的机会】✓
 *
 *  ★★★ 语义（★ 拍板 A）✗：
 *    · 第 1 次 IWDG 复位 ⇒ 【照旧自动回退】（自愈优先 ✓）
 *    · ★★ 第 2 次（说明回退也没救回来）⇒ **不再擦写** ⇒ 停在升级模式等 PC ✓
 *      （理由：回退都救不回 ⇒ 问题【不在版本上】⇒ 该人来看了 ✓）
 *
 *  ★ 寄存器选择 ✗：`BKP_DR4` 被低功耗方案【预定】了（主动睡眠标记）✓
 *    ⇒ ★★ 用 **`BKP_DR6`** ✓（DR1/2/3/5 已占 ✓ DR4 预留 ✓）
 *
 *  ★ 掉电行为 ✗：没 VBAT ⇒ 掉电清零 ✓
 *    ★★ 而这正是想要的：**"连续"** 次数只在不断电时才有意义 ✓✓ */
#define BOOT_IWDG_RETRY_DR   BKP_DR6


/* ★ 初始化：★ 打开 PWR + BKP 时钟 ✗ 并【解锁备份域】✓
 *   ★★ 【必须在【任何 BKP 读写之前】调用 ✗ 否则【读出来是 0 ✗ 写了没效果】】✓✓ */
void BootFlag_Init(void);

/* ★★ 读标志 ✗：返回 1 = 【有升级请求】✓；0 = 没有 ✓ */
uint8_t BootFlag_IsUpgradeRequested(void);

/* ★★★ 清除请求 ✓（★ 升级【成功】之后必须调 ✗ 否则【永远停在升级模式】）*/
void BootFlag_ClearUpgrade(void);

/* ★★★★ 请求升级 ✓（★ 【App 侧】用这个 ✗ Bootloader 用不上 ✓）
 *   ★★ 注意 ✗：★ 本函数【只写标志 ✗ 不会复位】】✓
 *     · ★★★ 【调用者要【自己决定】什么时候 `NVIC_SystemReset()`】✓✓ */
void BootFlag_RequestUpgrade(void);

/*==============================================================================
 *  ★★★★ 回退请求（★ 2026-10-14 加 ✗ G5 用 ✓）
 *
 *  ★ 语义 ✗：★【"我要【回到备份】✗ 请去 W25Q64 拿旧版本"】✓
 *  ★★ 和升级标志【完全独立】✗ 用【另一个寄存器 + 另一个魔数】✓
 *    （★ 理由见上面 `BOOT_ROLLBACK_DR` 的说明 ✓）
 *
 *  ★★★ 谁写它 ✗：★ App 侧 `Golden_RequestRollback()`（★ PC 发 `R` ✓）
 *  ★★★★ 谁清它 ✗：★【恢复成功之后】✗ 由 Boot 清 ✓
 *    ★ 为什么【必须清**✗：★ 不清的话【每次开机都以为"要回退"】
 *      → 【会【反复恢复 ✗ 而且每次都白等好几秒】】✓✓
 *============================================================================*/
uint8_t BootFlag_IsRollbackRequested(void);
void    BootFlag_ClearRollback(void);

/* ★ 2026-10-18 加：IWDG 回退次数（★ 说明见上）✗ */
uint8_t BootFlag_GetIwdgRetry(void);     /* 读已尝试次数（0 = 还没试过 ✓）*/
void    BootFlag_IncIwdgRetry(void);     /* 每次决定"自动回退"前 +1 ✓ */
void    BootFlag_ClearIwdgRetry(void);   /* 升级成功 / 决定停升级模式时清 0 ✓ */

#endif
