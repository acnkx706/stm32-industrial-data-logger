#ifndef __CRC16_H
#define __CRC16_H

#include "stm32f10x.h"

/*==============================================================================
 *  Crc16 —— 通用 CRC-16 计算（阶段 3 · 记录校验）
 *
 *  ★ 为什么单独成模块：CRC 不是 SD 专属 ✗
 *    · SD 数据块 CRC（原在 SD_SPI.c 里，static ✗ 外部用不了）
 *    · ★ 记录校验 rec.crc（本次要用 ✓）
 *    · 将来文件校验/固件校验也要 ✓
 *    → 一处实现、多处使用 ✓✓（避免两份实现悄悄跑偏 ✗）
 *
 *  ★★ 算法参数（★ 这是【对外契约】✗ 和记录格式一样，PC 侧必须照此实现 ✓✓）
 *    ┌──────────────┬──────────────────────────────┐
 *    │ 名称         │ CRC-16/KERMIT                │
 *    │ Width        │ 16                           │
 *    │ Poly         │ 0x1021（★ 反射形式 0x8408 ✓）│
 *    │ Init         │ 0x0000                       │
 *    │ RefIn        │ true（反射输入 ✓）           │
 *    │ RefOut       │ true（反射输出 ✓）           │
 *    │ XorOut       │ 0x0000                       │
 *    │ Check        │ "123456789" → ★ 0x2189 ✓✓    │
 *    └──────────────┴──────────────────────────────┘
 *    ★ Check 值取自 CRC 目录的【官方校验值】✓ ——
 *      不是"跟记忆里的值对"✗（本项目 CRC 阶段就是这么定案的 ✓）
 *
 *  ★ 调用示例（记录校验）：
 *      rec.crc = Crc16_Kermit((const uint8_t *)&rec, 38u);
 *    ★ 记录布局：crc 在偏移 38、占 2 字节 ✓
 *      → 算【前 38 字节】正好【不包含 crc 自己】✓✓（不用先置 0，少一个坑 ✓）
 * ============================================================================*/

uint16_t Crc16_Kermit(const uint8_t *d, uint32_t len);
/* ★★★★ 2026-10-14 新增：CRC-16/XMODEM（★ SD 规范要求的那一个 ✓）
 *   ★ 多项式 0x1021 ✗ 初值 0 ✗ 【不反射 ✗ 高位先算】✓
 *   ★★ 判据（★ 契约 ✓）✗ "123456789" → 【0x31C3】✓ */
uint16_t Crc16_Xmodem(const uint8_t *d, uint32_t len);
#endif
