#ifndef __HC_SR04_H
#define __HC_SR04_H

/*==============================================================================
 *  ★★★ HC-SR04 超声波测距（2026-10-20 新建 ✓）
 *
 *  ★ 接线（★ 打样板上的丝印 ✓）：
 *      · ① 5V   ── 5V      （★ 它吃 5V ✗ 别接 3.3V ⇒ 测不远/不稳 ✓）
 *      · ② TRIG ── **PB5**  （★ 普通推挽输出 ✓）
 *      · ③ ECHO ── **PB6**  （★ = **TIM4_CH1** ⇒ 定时器输入捕获 ✓✓）
 *      · ④ GND  ── GND
 *
 *  ★★ 用法（**非阻塞** ✗ 千万别写成 while 等回波 ✓）：
 *      ① `HC_SR04_Start()`    发 12µs 触发脉冲，立刻返回
 *      ② 之后每隔 1ms 调一次 `HC_SR04_Poll(&mm)`
 *         · 回 0 = 还没测完（继续等）
 *         · 回 1 = 成功，`mm` 是距离（毫米）
 *         · 回 2 = 超时/无回波（★ 前方没东西、太远、或传感器没接 ✓）
 *
 *  ★★★ 为什么不写成"一个函数阻塞测完" ✗：
 *    · 回波最长约 **25ms**（4 米）✗ 阻塞等 = 这 25ms 这个任务什么都不干 ✓
 *    · ★ 而且本工程【不许用 `Delay_us`】✗（它关 SysTick ⇒ 拆 FreeRTOS 心跳 ✓✓）
 *    · ⇒ 拆成 Start/Poll 两半 ✗ 任务里用 `vTaskDelay(1)` 等 ✓
 *      （★ 这 25ms 里 CPU 全给了别的任务 ✓✓）
 *============================================================================*/

#include "stm32f10x.h"

/* 初始化（★ 返回 1 = 成功 ✓）*/
uint8_t HC_SR04_Init(void);

/* 发一次触发脉冲（★ 非阻塞 ✗ 12µs 后就返回 ✓）*/
void HC_SR04_Start(void);

/* 查结果：0 = 还没完 ✓ / 1 = 成功 ✓ / 2 = 超时或无回波 ✗ */
uint8_t HC_SR04_Poll(uint16_t *mm);

/* 调试用：上一次测到的**原始脉宽**（µs ✗ 未做有效性判断 ✓）*/
uint16_t HC_SR04_LastPulseUs(void);

/* ★ 诊断（2026-10-20 加 ✓）：捕获中断累计次数 / ECHO 当前电平
 *   · `edges` 不动 ⇒ **线上从来没有边沿**（没供电/没接/坏 ✓）
 *   · 手测：ECHO 短一下 3.3V ⇒ `edges` 应 +1~2 ✓ */
uint16_t HC_SR04_EdgeCount(void);
uint8_t  HC_SR04_EchoLevel(void);

#endif
