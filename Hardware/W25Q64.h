/*==============================================================================
 *  ★★★★★ W25Q64（8MB SPI NOR Flash）—— 记录仪的"第二块存储"
 *          （★ 2026-10-14 从 `裸机\11.1软件SPI读写W25Q64` 移植 ✓）
 *
 *  ★★★★ 为什么要它（★ 用途排序 ✗ 见 31 号 / 29 号 ✓）：
 *    · ★ **金副本 + 自动回滚** ← 【本次目标】✓
 *      · 把"上一版能跑的 App 镜像"存在 W25Q64 里 ✓
 *      · App 一旦【坏了【或者"有效但卡死"】】✗ Boot 能【自己把它救回来】✓✓
 *      · ★★ 【这是【按键自救】补不上的那半截】✗：
 *        【进了 Bootloader【还是需要一台 PC + 一个固件】】✓
 *    · ★★ 历史版本（★ 8MB ÷ 64KB ≈ 【128 个槽位】✗ 想存几版存几版 ✓）
 *    · ★★★ 以后可选：数据双保险（★ 但 8MB 只够约 2.7 小时原始记录 ✓）
 *
 *  ★★★★ 硬件事实（★ 记在代码里 ✗ 免得以后忘 ✓）：
 *    · ★ 容量 ✗ **8MB = 64Mbit** ✗ 地址 24 位（0x000000 ~ 0x7FFFFF）✓
 *    · ★★ 粒度 ✗ **页 256 B**（写）/ **扇区 4KB**（擦）/ **块 64KB**（擦）✓
 *      → ★★★ 【写之前【必须先擦】**✗ 而且【擦最小是 4KB】✓✓
 *    · ★★★★ 【位只能 **1→0**】✗ → 【所以"改一个字节"也要【先擦整扇区】】✓✓
 *    · ★ JEDEC ID = **`0xEF4017`**（★ EF=华邦 ✗ 4017=W25Q64 ✓）
 *      → 【**这就是接线是否正确的唯一判据**】✓✓
 *
 *  ★★★ 三层结构（★ 和 SD 驱动同源 ✗ 便于对照 ✓）：
 *    ```
 *    第 1 层  软件 SPI（GPIO 模拟）  —— 本文件 .c 上半部分
 *    第 2 层  W25Q64 指令（JEDEC/写使能/等 BUSY/页写/扇区擦/读）
 *    第 3 层  数据操作（ReadData / WriteData【自动拆页】/ EraseSector）
 *    ```
 *    ★★ 为什么不拆成 `MySPI.c` + `W25Q64.c` 两个文件 ✗：
 *      【本工程只有这一处用软件 SPI ✗ 拆开只会多一个文件要维护】✓
 *      （★ 和 `SD_SPI.c`【一个文件装两层】的风格一致 ✓）
 *
 *  ★★★★★ 引脚（★ **2026-10-14 第二次定案** ✗ 第一版被用户否掉了 ✓）
 *
 *    | 信号 | 引脚 | 说明 |
 *    |---|---|---|
 *    | SCK  | **PA8**  | ★ 软件 SPI ✗ 手动打拍 ✓ |
 *    | MISO | **PA11** | ★★ 配【上拉输入】✗ 悬空时读 0xFF ✗ 不会乱跑 ✓ |
 *    | MOSI | **PA12** | ✓ |
 *    | CS   | **PB13** | ★ 软件控制片选 ✓（★ 从光敏 DO 那里【腾出来的】✓）|
 *
 *  ★★★★ 【第一版为什么被否 ✗ 这条教训比引脚本身值钱】✗✓：
 *    · ★ 我第一版选的 **PB5/PB6/PB7/PB10** ✗
 *      【从代码看【确实空闲】（★ 已 grep 全工程确认 ✓）】✓
 *    · ★★ 但用户看的是**实物** ✗✓ ——
 *      【那几个脚【紧挨着 OLED 的 PB8/PB9】✗
 *      【在面包板上【被 OLED 那片线【物理占死】了】】✓✓
 *    → ★★★ 【【实物优先于代码清点**✗
 *      【"代码里没人用" ≠ "板子上还能插得进去"】】✓✓
 *
 *  ★★★ 用户给的【实物可用清单】✗：`PC13/14/15` ✗ `PB13` ✗ `PA8/11/12/15` ✓
 *    · ★ **PC14 / PC15** ✗✗ **【绝对不能用】**✓✓：
 *      【那是 RTC 的 32.768kHz 晶振】✗（★ 51 号表 ✓）
 *      ★★ 而实测日志里 RTC【正在正常工作】✗
 *        （★ `MyRTC: BDCR=0x00008103` ✗ **`LSEON` 是亮的** ✓）
 *      → ★★★ 【占了它们 = 【RTC 直接死 ✗ 时间全丢】】✓✓
 *    · ★★ **PC13** ✗ 【蓝板【板载 LED】】✗ 驱动能力弱（★ ≤3mA ✓）
 *      → 【当 SPI 信号脚【不合适】】✓
 *    · ★★★ **PA15** ✗ 它是 **JTAG 的 JTDI** ✗
 *      【要用就必须先【关 JTAG（只留 SWD）】】✗
 *      ★★ 【而【关错了会把 SWD 也关掉**✗ 【调试口就没了】】✓
 *        → 【恢复得靠 BOOT0 跳线 ✗ 【不值得为省一个脚冒这个险】】✓✓
 *    · ★★★★ **PB13** ✗ 【原来挂【光敏 DO】】✗
 *      ★ 用户明确说"**实际用不上**"✗ → 【腾出来】✓
 *      ★★ ⚠️ 【代价 ✗ 光敏的【数字量】没了 ✗ 但【模拟量（PA1）照旧】】✓
 *        （★ 记录里的 `light` 字段【来自 PA1 的 ADC ✗ 不受影响】✓✓）
 *
 *  ★★★ 【为什么【不用硬件 SPI1**✗✓：
 *    · ★ SPI1 已经被 SD 卡占了（★ PA4~PA7 ✓）✓
 *    · ★★ 更要紧的是 ✗ 【SD 那条线**今天刚被证明【一碰就崩】】✗✓
 *      → 【金副本是【救命数据】✗ 【不能和它共用一条物理总线】】✓✓
 *============================================================================*/

/* ---- 第 2 层：指令表（★ 只列【用得到的】✗ 全表见 W25Q64 手册 ✓）---------- */
#define W25_INS_WRITE_ENABLE        0x06u   /* ★ 每次写/擦【之前必须发】✓ */
#define W25_INS_READ_STATUS_1       0x05u   /* ★ 读状态寄存器 1 ✗ bit0 = BUSY ✓ */
#define W25_INS_PAGE_PROGRAM        0x02u   /* ★ 页写 ✗ 【最多 256 字节 ✗ 不许跨页】✓ */
#define W25_INS_SECTOR_ERASE_4KB    0x20u   /* ★ 扇区擦（★ 最小擦除单位 ✓）*/
#define W25_INS_BLOCK_ERASE_64KB    0xD8u   /* ★ 块擦（★ 大块擦更快 ✓）*/
#define W25_INS_READ_DATA           0x03u   /* ★ 读数据（★ 无长度限制 ✓）*/
#define W25_INS_JEDEC_ID            0x9Fu   /* ★★★ 读 ID ✗ 【接线验证就靠它】✓ */
#define W25_INS_CHIP_ERASE          0xC7u   /* ⚠️ 全片擦（★ 几十秒 ✗ 慎用 ✓）*/

#define W25_DUMMY                   0xFFu   /* ★ 读的时候"拱时钟"用 ✓ */

/* ---- 容量 / 粒度（★ 代码里到处要用 ✗ 定成宏 ✓）---------------------------- */
#define W25_SIZE                (8u * 1024u * 1024u)   /* ★ 8MB ✓ */
#define W25_PAGE_SIZE           256u                   /* ★ 页（写）✓ */
#define W25_SECTOR_SIZE         4096u                  /* ★ 扇区（擦）✓ */
#define W25_JEDEC_W25Q64        0xEF4017u              /* ★★★ 唯一判据 ✓ */

/* ---- 自检开关（★ 按约定【要能切换】✓）-------------------------------------
 *  ★ =1 ✗ 每次开机做一次【擦+写+读】自检 ✓
 *  ★★ =0 ✗ 只读 JEDEC（★ 正式跑关掉 ✗ 免得白磨那个扇区 ✓）
 *  ⚠️ ★★★ 自检会【擦掉】`W25_SELFTEST_ADDR` 那个扇区 ✗
 *    → 【所以它固定在【最后一个扇区】✗ 【永不给固件/备份用】】✓✓
 *
 *  ★★★★★ 【2026-10-14 改成 0 ✗ 实测教训换来的】**✗✓：
 *    · ★ 它在【接线验证期】功不可没 ✗
 *      （★ 第一版就是靠它证明【写的方向也通】✓
 *        ★★ 只读 JEDEC 【证明不了 MOSI / 擦除时序】✓）
 *    · ★★ 但【接线已经验证通过（★ JEDEC=0xEF4017 + selftest=0 ✓）】✗
 *      → 【它【每次开机白磨一个扇区】✗ 【而且占 App 的 Flash】】✓
 *    · ★★★ 而【App 当时【只剩 332 字节】】✗✓
 *      → 【关掉它是【最没有代价的一笔】**✓
 *    · ★★★★ 注意 ✗【JEDEC 那行打印【不受本开关控制】**✗
 *      → 【关了之后【照样能看到 `W25Q64: JEDEC = 0xEF4017`】✓✓
 *      （★ 想复验接线 ✗ 把它改回 1 再烧一次就行 ✓）
 *
 *  ★★★ 什么时候该改回 1 ✗✓：
 *    · 换了板子 / 换了 W25Q64 芯片
 *    · 重新焊过那四根线
 *    · 出现"备份写不进去"之类的怀疑 ✗ */
#define W25Q64_SELFTEST         0

/* ---- 扇区用途划分（★ 先定好 ✗ 免得以后打架 ✓）----------------------------
 *  ★ 0x000000 ~ 0x000FFF ✗ 【头扇区】镜像头（magic/size/crc/版本 ✓）
 *  ★★ 0x001000 ~ 0x00FFFF ✗ 【金副本】（★ 64KB ✗ 一份 App 镜像足够 ✓）
 *  ★★★ 0x010000 ~ ...      ✗ 【历史版本】（★ 每份按 64KB 对齐 ✓）
 *  ★★★★ 0x7FF000 ~ 0x7FFFFF ✗ **只给自检用**（★ 最后一个扇区 ✓）*/
#define W25_ADDR_HEADER         0x000000u
#define W25_ADDR_GOLDEN         0x001000u
#define W25_ADDR_HISTORY        0x010000u
#define W25_SELFTEST_ADDR       0x7FF000u

/*==============================================================================
 *  ★★★★ 对外接口（★ 全部返回"状态"✗ 不返回 void ✓）
 *
 *  ★ 为什么【失败必须能传出来**✗✓：
 *    · ★ 原版（江协教程）是 `void WaitBusy()` ✗ `void PageProgram()` ✓
 *    · ★★ 【超时了、写失败了 ✗ 【调用者完全不知道】】✓
 *      → ★★★ 【往金副本里写进一份坏镜像 ✗ 然后靠它去救砖 ✗ 必炸】✓✓
 *    → ★★★★ 【所以这里【每一个会失败的操作【都返回状态】】✓✓
 *============================================================================*/

/* ★ 初始化（★ 配 GPIO + 探测 ✗ 返回 1 = 【芯片在位】✓）*/
uint8_t  W25Q64_Init(void);

/* ★★ 读 JEDEC ID（★ 24 位 ✗ 正常应为 `0xEF4017` ✓）*/
uint32_t W25Q64_ReadJEDEC(void);

/* ★★★ 芯片在位吗（★ = JEDEC 等于 `0xEF4017` ✓）*/
uint8_t  W25Q64_IsPresent(void);

/* ★★★ 读（★ 无长度限制 ✗ 可跨页跨扇区 ✓）✗ 返回 1 = OK ✓ */
uint8_t  W25Q64_ReadData(uint32_t addr, uint8_t *buf, uint32_t len);

/* ★★★★ 写（★ **自动按 256B 页边界拆开**✓ 返回 1 = OK ✓）
 *  ⚠️ ★★ 【目标区域必须【已经擦过】】✗ 否则写出来是"旧值 AND 新值" ✗ 静默错 ✓ */
uint8_t  W25Q64_WriteData(uint32_t addr, const uint8_t *buf, uint32_t len);

/* ★★★ 擦一个 4KB 扇区（★ 返回 1 = OK ✓）
 *  ★★ 超时上限按【4KB 擦除最坏 400ms】留够 ✗ 见 .c 里的 `W25_WAIT_TIMEOUT` ✓ */
uint8_t  W25Q64_EraseSector(uint32_t addr);

/* ★★★ 擦一个 64KB 块（★ 返回 1 = OK ✓）
 *  ★ 为什么要有它 ✗：★ 备份一份 51KB 的 App 镜像时 ✗
 *    【擦一个 64KB 块 ≪ 擦 16 个 4KB 扇区】（★ 后者要 16 次等 BUSY ✓）✓ */
uint8_t  W25Q64_EraseBlock64K(uint32_t addr);

/* ★ 等 BUSY 清（★ 返回 1 = 好了 ✗ 0 = 超时 ✓）*/
uint8_t  W25Q64_WaitReady(void);

/* ★★★★ 自检（★ 擦 → 写 → 读回比对 ✓）
 *  ★ 返回 ✗ 0 = 【全过】✗ 非 0 = 【第几步坏的】✓
 *  ★★ 判据位置 ✗ `W25_SELFTEST_ADDR`（★ 最后一个扇区 ✓）*/
uint8_t  W25Q64_SelfTest(void);

