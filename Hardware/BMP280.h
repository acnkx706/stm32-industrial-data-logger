#ifndef __BMP280_H
#define __BMP280_H

#include "stm32f10x.h"

/*==============================================================================
 *  BMP280 气压/温度计驱动（2026-10-09 接入）
 *
 *  ★ 器件已实测确认（不靠丝印猜 ✓）：
 *      I2C 地址 = 0x76 ✓    ID 寄存器 0xD0 = 0x58 ✓（= BMP280 ✓）
 *      （BMP580 家族在 0x46/0x47、ID 在 0x01；BME280 的 ID 是 0x60 —— 都不是 ✓）
 *  ★ 与 MPU6050 共用软件 I2C：PA2 = SCL / PA3 = SDA ✓（地址 0x68 vs 0x76 不冲突 ✓）
 *
 *  ★ 对外单位（对齐 `30` 号 §15.2 的记录格式契约 ✓ 不要改 ✗）：
 *      press         = ×10 Pa ✓（0.1 Pa 分辨率）→ 1013.25 hPa = 1013250 ✓
 *      temp（可选）  = ×100 °C ✓（0.01 °C）
 *    ★ 读失败 / 未接 → 返回 0 ✓（符合"未接字段填约定值"的规矩 ✓）
 *
 *  ★ 实测提醒（免得以后误判传感器坏了 ✗）：
 *      BMP280 的【实际噪声约 ±10 Pa】✗ —— 所以读数会有几十 Pa 的抖动 ✓
 *      那是正常的 ✓ 不是故障 ✓（要更稳得靠过采样/平均 ✓）
 * ============================================================================*/

#define BMP280_I2C_ADDR     0x76
#define BMP280_ID_EXPECT    0x58

/* 返回：0 = OK / 1 = ID 不对（型号不符）/ 2 = 总线无应答（没接上或供电问题）*/
uint8_t BMP280_Init(void);

/* 读一次（内部：触发单次测量 → 等完成 → 读 6 字节 → 定点补偿 ✓）
 * 返回：0 = OK / 其它 = 失败（此时 *press_x10pa / *temp_c100 原样不动 ✓）
 * ★ 单位：*press_x10pa = ×10 Pa ✓；*temp_c100 = ×100 °C ✓（传 NULL 可只读其一 ✓）*/
uint8_t BMP280_Read(int32_t *press_x10pa, int32_t *temp_c100);

/* ★ 自检：用数据手册的官方算例跑一遍补偿公式 ✓
 *   返回 1 = 通过 ✓（说明公式与常量搬运无误 ✓）
 *   ⚠️ 算例常量是凭记忆写入手册值 ✗ —— 第一次跑必须核对：
 *      若这里不过 ✗，先怀疑"我抄的算例值"✗，不要先怀疑公式 ✓（两处分开验证 ✓）*/
uint8_t BMP280_SelfTest(void);

#endif
