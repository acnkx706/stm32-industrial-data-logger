#ifndef __KEY_H
#define __KEY_H

/*
 * 按键驱动接口（非阻塞版）
 *
 * 设计约定：
 *  1. 驱动层零延时：消抖靠任务以 20ms 周期调 Key_Scan()，本文件内禁止出现
 *     vTaskDelay / Delay_ms / while 死等——延时混进驱动 = 调用任务被绑架。
 *  2. 事件位图：一次扫描把两个键都扫完，用一个字节报告"这次扫描发生了什么"。
 *     调用方只有一处，结构上杜绝"轮询每个键函数、漏扫/重复消费"的老坑。
 *  3. 驱动只报事件不做业务：谁按下、什么含义，由任务层决定（freertos_demo.c）。
 */

/* 事件位定义（Key_Scan 返回值用） */
#define KEY1_EVENT      0x01    /* PB1 确认按下（消抖后只报一次，松手前不再报） */
#define KEY11_EVENT     0x02    /* PB11 确认按下 */
#define KEY_PWR_EVENT   0x04    /* ★ PA0 长按满 1 秒才报一次（2026-10-13 新增） */
#define KEY_PWR_SHORT_EVENT 0x08 /* ★ 2026-11-09 加：PA0 按下后松手、且没到长按阈值
                                  *   用途：电源键改成"短按暂停 / 长按关机"两用
                                  *   判据：按住 ≥3 拍（60ms）算确认，<50 拍（1s）才算短按
                                  *   两个事件互斥：报过长按就不会再报短按 */

/* 两个键同时确认按下时的返回值 = KEY1_EVENT | KEY11_EVENT = 0x03 */

/*==============================================================================
 *  ★ 实测纠正按键的接线极性（2026-10-13 深夜，用户按实物确认）
 *
 *  ★ 事实：按键一端接 3.3V，另一端接引脚
 *    ★ GPIO 配 IPD（下拉）→ 空闲 = 0，按下 = 1
 *
 *  ★ 为什么必须把这条写进头文件：
 *    · stm32\学习笔记\51-全系统接线清单.md 原来写的是
 *      「按键另一端接 GND」，以及「按键接成了 3.3V，必须接 GND」
 *      → 那两条都是错的!!
 *    · 按那条接会怎样：
 *      · IPD 下拉 + 另一端接 GND→ 松开和按下都是 0
 *      · → 按键彻底失效，而且现象看起来像"驱动坏了"，查半天
 *    · 判据（用户实测，不是推断）：
 *      ★ 按一下 KEY1，OLED 第 4 行的 RUN / PAUSE
 *      每次都正常翻转 → 证明按下确实读到了 1
 *      （若接的是 GND，则一次都不会动）
 *
 *  → 51 号那份表已经同步改过来，两边现在一致，
 *    ★ 以后改接线以本注释 + 实测为准，别只信文档
 *============================================================================*/

/*==============================================================================
 *  ★ 电源键（2026-10-13 新增）—— 安全关机 / 恢复
 *
 *  ★ 硬件（和 KEY1/KEY2 同一极性，接线最容易的地方就在这）：
 *    · 一端 → PA0，另一端 → 3.3V
 *    · 不需要任何外部电阻—— 内部下拉负责"松开时保证是 0"
 *
 *  ★ 为什么选 PA0：
 *    · 全工程只有它空着（已核对 AD.c
 *      GPIO_Pin_0 那一行打的是 GPIOB，是 PB0 的电池分压）
 *    · 而 PA0 就是 WKUP 引脚（EXTI0）
 *      → 以后做"按键开机 + 自锁断电"时正好需要它来唤醒
 *        （现在接上，等于给那一步铺好路）
 *
 *  ★ 用法：长按满 1 秒才触发，短按什么都不做
 *    · 为什么不用短按：记录仪无人值守
 *      短按太容易被误触（箱子压住 / 线搭上去）
 *    · 为什么报过之后必须松手才能再触发：
 *      否则按住不放 = 反复开关机
 *
 *  ★ 按下之后发生什么（详见 freertos_demo.c 的 task_KEY）：
 *    · 第一次长按 → 安全关机（落盘 + 关文件 + 屏显 SAFE TO OFF）
 *    · 再长按一次 → 恢复记录（不用断电，相当于一个软开关）
 *============================================================================*/

void Key_Init(void);
uint8_t Key_Scan(void);

#endif
